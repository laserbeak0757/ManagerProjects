-- Tabla: auth.parametro
-- ConfiguraciÃ³n global del sistema de autenticaciÃ³n. PatrÃ³n key-value con
-- tipado fuerte: cada parÃ¡metro tiene un nombre Ãºnico en formato
-- namespace.nombre (ej. login.intentos_maximos) y se almacena en la columna
