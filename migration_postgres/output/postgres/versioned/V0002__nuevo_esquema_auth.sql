 id_parametro INTEGER generated by default as generated by default as identity NOT NULL,
 nombre_parametro VARCHAR(100) NOT NULL,
 tipo_dato VARCHAR(20) NOT NULL,
 valor_numerico INTEGER NULL,
 valor_varchar varchar(500) NULL,
